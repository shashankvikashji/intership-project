import { useEffect, useState } from 'react';
import { Sparkles } from 'lucide-react';
import api from '../lib/api';

export default function AiSummary({ articleId }) {
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  useEffect(() => {
    let alive = true;
    setLoading(true);
    setError('');
    api.get(`/ai/summary/${articleId}`)
      .then(({ data }) => { if (alive) setData(data); })
      .catch(err => {
        if (!alive) return;
        const status = err.response?.status;
        setError(
          status === 429 ? 'AI service is rate-limited right now. The full article is still available above.'
          : status === 422 ? 'This story has too little text to summarize yet.'
          : 'Summary is unavailable right now. The full article is still available above.'
        );
      })
      .finally(() => { if (alive) setLoading(false); });
    return () => { alive = false; };
  }, [articleId]);

  return (
    <section aria-label="AI summary" className="mt-8 rounded-lg border border-accent/25 bg-surface">
      <div className="flex items-center gap-2 border-b border-border px-4 py-3">
        <Sparkles size={15} className="text-accentHover" />
        <h2 className="text-[13px] font-semibold uppercase tracking-[0.08em] text-paper">AI summary</h2>
        {data && (
          <span className="ml-auto text-[11.5px] text-muted">
            {data.source === 'ai' ? `Generated by AI${data.cached ? ' · cached' : ''}` : 'Key sentences from the article'}
          </span>
        )}
      </div>
      <div className="px-4 py-3">
        {loading && (
          <div className="space-y-2 py-1" aria-label="Loading summary">
            {[0, 1, 2].map(i => <div key={i} className="h-4 animate-pulse rounded bg-surface2" style={{ width: `${92 - i * 12}%` }} />)}
          </div>
        )}
        {error && !loading && <p className="py-1 text-[13.5px] text-muted">{error}</p>}
        {data && !loading && (
          <div className="py-1">
            {data.keyPoints?.length > 0 && (
              <ul className="space-y-1.5">
                {data.keyPoints.map((p, i) => (
                  <li key={i} className="flex gap-2 text-[14px] leading-relaxed text-paper/90">
                    <span aria-hidden="true" className="mt-0.5 shrink-0 text-accentHover">•</span>
                    <span>{p}</span>
                  </li>
                ))}
              </ul>
            )}
            {data.whyItMatters && (
              <p className="mt-3 text-[13.5px] leading-relaxed text-muted">
                <span className="font-medium text-paper">Why it matters: </span>{data.whyItMatters}
              </p>
            )}
            {data.whatsNext && (
              <p className="mt-1.5 text-[13.5px] leading-relaxed text-muted">
                <span className="font-medium text-paper">What happens next: </span>{data.whatsNext}
              </p>
            )}
          </div>
        )}
      </div>
    </section>
  );
}
